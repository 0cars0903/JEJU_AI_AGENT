def empty():
    return {"type": None, "metric": [], "target": None, "space": [], "time": None, "time_year": None, "breakdown": None, "cond": [], "form": None, "expect": "답함"}


def validate(t):
    """칸 값이 닫힌 목록 안에 있는지 검사. 틀린 칸 이름 목록을 돌려준다(검수의 '해석 오류')."""
    bad = []
    if t.get("type") not in TYPES:
        bad.append("type")
    if any(m not in METRICS for m in t.get("metric") or []):
        bad.append("metric")
    if t.get("target") not in [None, *TARGETS_BIZ, *TARGETS_POP, *TARGETS_OUT]:
        bad.append("target")
    if any(s not in DONGS for s in t.get("space") or []):
        bad.append("space")
    if t.get("time") not in [None, *TIMES]:
        bad.append("time")
    if t.get("breakdown") not in [None, *BREAKDOWNS]:
        bad.append("breakdown")
    if any(c not in CONDS for c in t.get("cond") or []):
        bad.append("cond")
    if t.get("expect") not in EXPECTS:
        bad.append("expect")
    return bad


